def get_allotment_per_share(shares_per_10):
    """根据"配售10张所需股数"计算每股配债额(元面值)"""
    return 1000.0 / shares_per_10 if shares_per_10 > 0 else 0.0


def calc_cushion(stock_price, shares_per_10, premium_pct=20.0):
    """
    计算安全垫（%）
    公式: 百元含权 = (100 / 股价) × (1000 / 配10张所需股数)
         安全垫   = 百元含权 × 溢价率 / 100 × 100%
                   = 百元含权 × 溢价率（小数）
    """
    if stock_price <= 0 or shares_per_10 <= 0:
        return 0.0
    allotment = 1000.0 / shares_per_10
    hundred_rights = (100.0 / stock_price) * allotment  # 百元含权(元面值)
    cushion = hundred_rights * (premium_pct / 100.0)      # 安全垫(%)
    return cushion


def get_rating(cushion):
    if cushion >= 5.0:
        return "★★★★★", "high"
    elif cushion >= 3.0:
        return "★★★★☆", "mid"
    elif cushion >= 1.5:
        return "★★★☆☆", "low"
    else:
        return "★★☆☆☆", "none"


def to_dict(row, premium_pct=20.0):
    """将一行数据转为字典，含计算字段"""
    (orig_code, bond_code, orig_name, bond_name, scale, rating,
     stock_price, shares_per_10, record_date, apply_date, listing_date) = row

    allotment = get_allotment_per_share(shares_per_10)
    hundred_rights = (100.0 / stock_price) * allotment if stock_price > 0 else 0.0
    cushion = calc_cushion(stock_price, shares_per_10, premium_pct)
    star, level = get_rating(cushion)

    return {
        "orig_code": orig_code,
        "bond_code": bond_code,
        "orig_name": orig_name,
        "bond_name": bond_name,
        "scale": scale,
        "rating": rating,
        "stock_price": stock_price,
        "shares_per_10": shares_per_10,
        "allotment": round(allotment, 4),
        "hundred_rights": round(hundred_rights, 2),
        "cushion": round(cushion, 2),
        "cushion_15": round(hundred_rights * 0.15, 2),
        "star": star,
        "level": level,
        "record_date": record_date,
        "apply_date": apply_date,
        "listing_date": listing_date,
    }


def get_all_sorted(premium_pct=20.0):
    """返回按安全垫降序排列的所有数据"""
    result = [to_dict(r, premium_pct) for r in BOND_DATA]
    result.sort(key=lambda x: x["cushion"], reverse=True)
    return result


